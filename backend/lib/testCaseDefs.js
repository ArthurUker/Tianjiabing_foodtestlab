/** 用例 id → 定义 的扁平索引 */
export function indexCaseDefs(defs = CASE_DEFS) {
  const map = new Map()
  for (const g of defs) {
    for (const c of g.cases) map.set(c.id, { ...c, group: g.group, groupName: g.groupName })
  }
  return map
}
